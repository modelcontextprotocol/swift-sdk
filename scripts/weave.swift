// Generates docs/*.md from docs/src/*.src.md, and README.md from
// README.src.md, and checks the docs.
//
//   swift scripts/weave.swift            write docs/*.md and README.md
//   swift scripts/weave.swift --check    fail if they are stale or links are broken
//
// In a .src.md file, a line `%include <path> <region>` is replaced by a
// Swift code block with the lines between `// snippet: <region>` and
// `// endsnippet` in <path> (relative to the repository root), dedented.
// Snippets live in compiled targets under Examples/, so `swift build`
// checks every snippet.
//
// Checks: every `## ` section of the feature guides is linked from
// docs/README.md, and every relative Markdown link to docs resolves to a
// file and heading.

import Foundation

let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let docs = root.appendingPathComponent("docs")
let sources = docs.appendingPathComponent("src")
let check = CommandLine.arguments.contains("--check")
let featureGuides = ["protocol.md", "server.md", "client.md"]

var problems: [String] = []

func read(_ url: URL) -> String? { try? String(contentsOf: url, encoding: .utf8) }

/// The lines of a snippet region, dedented.
func snippet(_ path: String, _ region: String, from source: String) -> String? {
    guard let text = read(root.appendingPathComponent(path)) else {
        problems.append("\(source): \(path) not found")
        return nil
    }
    var lines: [Substring] = []
    var inside = false
    var found = false
    for line in text.split(separator: "\n", omittingEmptySubsequences: false) {
        let trimmed = line.trimmingCharacters(in: .whitespaces)
        if trimmed == "// snippet: \(region)" {
            inside = true
            found = true
            continue
        }
        if inside, trimmed == "// endsnippet" { break }
        if inside { lines.append(line) }
    }
    guard found else {
        problems.append("\(source): region '\(region)' not found in \(path)")
        return nil
    }
    let indent =
        lines.filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
        .map { $0.prefix(while: { $0 == " " }).count }.min() ?? 0
    return lines.map { $0.count >= indent ? String($0.dropFirst(indent)) : "" }.joined(separator: "\n")
}

func weave(_ source: URL) -> String {
    let name = "docs/src/" + source.lastPathComponent
    var output = ["<!-- Generated by scripts/weave.swift from \(name). Do not edit. -->", ""]
    for line in (read(source) ?? "").split(separator: "\n", omittingEmptySubsequences: false) {
        if line.hasPrefix("%include ") {
            let parts = line.split(separator: " ").map(String.init)
            guard parts.count == 3 else {
                problems.append("\(name): malformed directive '\(line)'")
                continue
            }
            if let code = snippet(parts[1], parts[2], from: name) {
                output += ["```swift", code, "```"]
            }
        } else {
            output.append(String(line))
        }
    }
    return output.joined(separator: "\n")
}

/// GitHub's heading anchor.
func slug(_ heading: String) -> String {
    let text = heading.lowercased().replacingOccurrences(of: "`", with: "")
    var result = ""
    for scalar in text.unicodeScalars {
        if CharacterSet.alphanumerics.contains(scalar) || scalar == "-" || scalar == "_" {
            result.unicodeScalars.append(scalar)
        } else if scalar == " " {
            result.append("-")
        }
    }
    return result
}

/// The anchors of a Markdown document, outside code blocks.
func anchors(_ text: String) -> (all: Set<String>, sections: [(String, String)]) {
    var all: Set<String> = []
    var counts: [String: Int] = [:]
    var sections: [(String, String)] = []
    var fenced = false
    for line in text.split(separator: "\n") {
        if line.hasPrefix("```") { fenced.toggle() }
        guard !fenced, line.hasPrefix("#") else { continue }
        let title = line.drop(while: { $0 == "#" }).trimmingCharacters(in: .whitespaces)
        var anchor = slug(title)
        if let count = counts[anchor] {
            counts[anchor] = count + 1
            anchor += "-\(count)"
        } else {
            counts[anchor] = 1
        }
        all.insert(anchor)
        if line.hasPrefix("## ") { sections.append((title, anchor)) }
    }
    return (all, sections)
}

// 1. Weave.
let fileManager = FileManager.default
let srcFiles = ((try? fileManager.contentsOfDirectory(atPath: sources.path)) ?? [])
    .filter { $0.hasSuffix(".src.md") }.sorted()
if srcFiles.isEmpty { problems.append("no docs/src/*.src.md files") }
var generated: [String: String] = [:]
for file in srcFiles {
    let target = String(file.dropLast(".src.md".count)) + ".md"
    let text = weave(sources.appendingPathComponent(file))
    generated[target] = text
    let url = docs.appendingPathComponent(target)
    if check {
        if read(url) != text { problems.append("docs/\(target) is stale: run swift scripts/weave.swift") }
    } else {
        try text.write(to: url, atomically: true, encoding: .utf8)
    }
}

// The repository README is woven the same way; its links are not checked.
let rootSource = root.appendingPathComponent("README.src.md")
if fileManager.fileExists(atPath: rootSource.path) {
    let text = weave(rootSource).replacingOccurrences(
        of: "from docs/src/README.src.md", with: "from README.src.md")
    let url = root.appendingPathComponent("README.md")
    if check {
        if read(url) != text { problems.append("README.md is stale: run swift scripts/weave.swift") }
    } else {
        try text.write(to: url, atomically: true, encoding: .utf8)
    }
}

// 2. Links.
let linkPattern = try NSRegularExpression(pattern: #"\]\(([^)\s]+)\)"#)
var documentAnchors: [String: Set<String>] = [:]
for (file, text) in generated { documentAnchors[file] = anchors(text).all }
for (file, text) in generated {
    var fenced = false
    for line in text.split(separator: "\n") {
        if line.hasPrefix("```") { fenced.toggle() }
        if fenced { continue }
        let string = String(line)
        for match in linkPattern.matches(in: string, range: NSRange(string.startIndex..., in: string)) {
            let target = (string as NSString).substring(with: match.range(at: 1))
            if target.contains("://") || target.hasPrefix("mailto:") { continue }
            let parts = target.split(separator: "#", maxSplits: 1, omittingEmptySubsequences: false)
            let path = String(parts[0])
            let anchor = parts.count > 1 ? String(parts[1]) : nil
            let document = path.isEmpty ? file : path
            if document.hasSuffix(".md"), !document.contains("/") {
                guard let known = documentAnchors[document] else {
                    problems.append("docs/\(file): link to missing docs/\(document)")
                    continue
                }
                if let anchor, !known.contains(anchor) {
                    problems.append("docs/\(file): link to missing heading \(document)#\(anchor)")
                }
            } else if !path.isEmpty {
                let resolved = docs.appendingPathComponent(path).standardizedFileURL.path
                if !fileManager.fileExists(atPath: resolved) {
                    problems.append("docs/\(file): link to missing file \(path)")
                }
            }
        }
    }
}

// 3. The index links every section of the feature guides.
if let index = generated["README.md"] {
    for guide in featureGuides {
        guard let text = generated[guide] else {
            problems.append("docs/\(guide) is missing")
            continue
        }
        for (title, anchor) in anchors(text).sections where !index.contains("(\(guide)#\(anchor))") {
            problems.append("docs/README.md does not link \(guide)#\(anchor) (\(title))")
        }
    }
} else {
    problems.append("docs/README.md is missing")
}

if !problems.isEmpty {
    FileHandle.standardError.write(Data((problems.joined(separator: "\n") + "\n").utf8))
    exit(1)
}
print(check ? "docs are up to date" : "wrote \(generated.count) files to docs/")
