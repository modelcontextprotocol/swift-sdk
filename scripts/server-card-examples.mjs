#!/usr/bin/env node
// Regenerates Tests/MCPTests/Generated/ServerCardExamples.swift from the
// examples of the Server Card extension (SEP-2127) at the pinned commit.
//
// Usage: node scripts/server-card-examples.mjs
//
// Each example is copied verbatim with its SHA-256, which the tests check.
// To follow a newer revision of the extension, change `commit`, run this
// script, and update the pin in Sources/MCP/Base/ServerCard.swift and
// design/server_cards.md.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repository = 'modelcontextprotocol/ext-server-card';
const commit = '526201bbc80231daa40ffcdecfc9da4e54e5dc93';
const examples = [
  'examples/ServerCard/valid/minimal.json',
  'examples/ServerCard/valid/templated-remote.json',
  'examples/ServerCard/invalid/bad-name-pattern.json',
  'examples/ServerCard/invalid/date-versioned-schema.json',
  'examples/ServerCard/invalid/missing-name.json',
  'examples/ServerCard/invalid/missing-schema.json',
  'examples/ServerCard/invalid/wrong-schema-name.json',
];

const entries = [];
for (const path of examples) {
  const response = await fetch(`https://raw.githubusercontent.com/${repository}/${commit}/${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  const text = await response.text();
  if (text.includes('"""#')) throw new Error(`${path}: cannot be a raw string literal`);
  const sha256 = createHash('sha256').update(text, 'utf8').digest('hex');
  const trailingNewline = text.endsWith('\n');
  const body = trailingNewline ? text.slice(0, -1) : text;
  entries.push(
    `    ServerCardExample(\n` +
      `        path: "${path}",\n` +
      `        sha256: "${sha256}",\n` +
      `        trailingNewline: ${trailingNewline},\n` +
      `        text: #"""\n${body}\n"""#),`,
  );
}

const output = `// Generated by scripts/server-card-examples.mjs; do not edit.
//
// The examples of ${repository} at ${commit}.

struct ServerCardExample {
    let path: String
    let sha256: String
    let trailingNewline: Bool
    let text: String

    /// The file as published.
    var contents: String { trailingNewline ? text + "\\n" : text }
    var isValid: Bool { path.contains("/valid/") }
}

let serverCardExamplesCommit = "${commit}"

let serverCardExamples: [ServerCardExample] = [
${entries.join('\n')}
]
`;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(join(root, 'Tests/MCPTests/Generated/ServerCardExamples.swift'), output);
console.log(`wrote ${examples.length} examples`);
